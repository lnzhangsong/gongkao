import type { Article, ArticleTopic } from '../types'

function mins(paragraphs: string[]): number {
  const chars = paragraphs.join('').length + 200
  return Math.max(3, Math.round(chars / 380))
}

interface Seed {
  title: string
  summary: string
  topic: ArticleTopic
  source: Article['source']
  date: string
  paragraphs: string[]
  pullquote?: string
  finishNote?: string
  featured?: boolean
}

let seq = 12
function mk(seed: Seed): Article {
  seq += 1
  return {
    id: `a${String(seq).padStart(2, '0')}`,
    title: seed.title,
    summary: seed.summary,
    content: seed.paragraphs,
    pullquote: seed.pullquote,
    finishNote: seed.finishNote,
    source: seed.source,
    topic: seed.topic,
    date: seed.date,
    readTime: mins(seed.paragraphs),
    featured: seed.featured,
  }
}

